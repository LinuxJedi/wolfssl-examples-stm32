static int current_led = 0;
static inline void LED_Set(uint8_t idx, bool on)
{
  uint16_t pin;
  switch(idx) {
    case 0: pin = GPIO_PIN_12; break;
    case 1: pin = GPIO_PIN_13; break;
    case 2: pin = GPIO_PIN_14; break;
    default: pin = GPIO_PIN_15; break;
  }

  HAL_GPIO_WritePin(GPIOB, pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}
static inline void LED_Set_Change()
{

  switch(current_led) {
    case 0:
    	LED_Set(3, false);
    	LED_Set(0, true);
    	break;
    case 1:
    	LED_Set(0, false);
    	LED_Set(1, true);
    	break;
    case 2:
    	LED_Set(1, false);
    	LED_Set(2, true);
    	break;
    default:
    	LED_Set(2, false);
    	LED_Set(3, true);
    	break;
  }

  current_led++;
  if (current_led == 4)
	  current_led = 0;
}

