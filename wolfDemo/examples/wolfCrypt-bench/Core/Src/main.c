/* ---- Software-PWM parameters ----
   With 64 levels and a 1 kHz PWM frequency, we need a 64 kHz TIM6 update IRQ.
   That’s light CPU load and gives smooth fades.
*/
#define PWM_LEVELS        64u            // 6-bit PWM
#define PWM_FREQ_HZ       1000u          // visible PWM ~1 kHz (no flicker)
#define TIM6_TICK_HZ      (PWM_LEVELS * PWM_FREQ_HZ) // = 64 kHz

/* Fade sequencing: one LED at a time, fade up then down, then next LED */
#define FADE_STEP_PERIODS 2u             // brightness change every N PWM periods
#define BRIGHT_MAX        (PWM_LEVELS-1)

static volatile uint8_t  pwm_phase = 0;   // 0..(PWM_LEVELS-1)
