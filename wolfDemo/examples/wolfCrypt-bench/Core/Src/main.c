/* Called every TIM6 tick: keep as-is */
static void LED_ApplyPWM(void)
{
  uint8_t p = pwm_phase;

  for (uint8_t i = 0; i < 4; i++) {
    LED_Set(i, bright[i] > p);
  }

  p++;
  if (p >= PWM_LEVELS) {
    p = 0;
    if (++period_acc >= FADE_STEP_PERIODS) {
      period_acc = 0;
      LED_FadeStep();
    }
  }
  pwm_phase = p;
}

/* Cross-fade:
   - trail_led brightness = BRIGHT_MAX - cross (fading down)
   - lead_led  brightness = cross               (fading up)
   When cross reaches BRIGHT_MAX, advance to next LED and reset cross.
*/
static void LED_FadeStep(void)
{
  /* Update the two active LEDs */
  bright[lead_led]  = cross;
  bright[trail_led] = BRIGHT_MAX - cross;

  /* Others stay off */
  for (uint8_t i = 0; i < 4; i++) {
    if (i != lead_led && i != trail_led) bright[i] = 0;
  }

  /* Advance cross */
  if (cross < BRIGHT_MAX) {
    cross++;
  } else {
    /* Completed cross-fade: the lead becomes the new trail,
       pick the next LED as the new lead, reset cross */
    cross = 0;
    trail_led = lead_led;
    lead_led  = (uint8_t)((lead_led + 1) & 0x03);
  }
}
