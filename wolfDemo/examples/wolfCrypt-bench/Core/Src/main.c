static volatile uint8_t  lead_led = 0;     // 0..3 (PB12..PB15)
static volatile uint8_t  trail_led = 3;    // previous LED (starts as 3 so 3->0 first)
static volatile uint8_t  cross = 0;        // 0..BRIGHT_MAX
